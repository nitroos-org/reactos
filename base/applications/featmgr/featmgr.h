#define FM_MAX_ID    64
#define FM_MAX_NAME  128
#define FM_MAX_DESC  512
#define FM_MAX_VER   32
#define FM_MAX_DEPS  256

/* Two-tier model (see design doc): OS features vs additional software. */
typedef enum _FM_TIER
{
    FM_TIER_OS = 0,       /* optional OS component/subsystem/driver */
    FM_TIER_SOFTWARE = 1  /* installable app/package (RAPPS-successor tier) */
} FM_TIER;

/* Installed-state, DISM /Get-Features-like, persisted in the registry. */
typedef enum _FM_STATE
{
    FM_STATE_NOT_INSTALLED = 0, /* known in catalog, never enabled */
    FM_STATE_ENABLED = 1,       /* payload applied, reversible undo recorded */
    FM_STATE_DISABLED = 2       /* previously enabled, now reverted */
} FM_STATE;

typedef struct _FM_FEATURE
{
    WCHAR   Id[FM_MAX_ID];
    WCHAR   Name[FM_MAX_NAME];
    WCHAR   Description[FM_MAX_DESC];
    WCHAR   Version[FM_MAX_VER];
    WCHAR   Dependencies[FM_MAX_DEPS];
    WCHAR   ManifestPath[MAX_PATH];
    FM_TIER Tier;
    FM_STATE State;
    BOOL    Removable;           /* Removable=0 in catalog: base component, disable refused */
    BOOL    PayloadAvailable;    /* every declared payload source present on disk */
    WCHAR   InstallDate[32];     /* UTC ISO-8601 of last enable, "" if never */
    BOOL    PendingReboot;       /* disabled but some component awaits reboot-delete */
    WCHAR   Provider[16];        /* software tier: [Install] Provider= "rapps" | "command" | "scoop"; "" for OS tier */
    WCHAR   Source[32];          /* software tier display source: "rapps", "command", "scoop/<bucket>"; "" for OS tier */
    WCHAR   App[48];             /* Provider=scoop: [Scoop] App (the Scoop app name) */
    WCHAR   Detect[128];         /* software tier: raw [Install] DetectPath (installed iff the path exists) */
    WCHAR   Group[48];           /* [Feature] Group: the parent node of the Turn-features-on-or-off tree ("" = by tier) */
    WCHAR   Bucket[24];          /* Provider=scoop: the bucket the entry came from */
    WCHAR   Homepage[160];       /* Provider=scoop: [Scoop] Homepage (truncated) */
    WCHAR   License[48];         /* Provider=scoop: [Scoop] License */
    BOOL    Verified;            /* Provider=scoop: the manifest has a hash Scoop can check the download against */
    WCHAR   InstalledVersion[FM_MAX_VER]; /* "" unless installed. Scoop: apps\<app>\current\manifest.json;
                                           * others: the Version recorded when featmgr enabled it */
    BOOL    UpdateAvailable;     /* Provider=scoop, installed, and the imported catalog has a newer version */
} FM_FEATURE;

