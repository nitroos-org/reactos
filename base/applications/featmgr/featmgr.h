/* ---- Scoop (SCOOP-FEATMGR-01) ---------------------------------------------
 * Provider=scoop entries are generated from a Scoop bucket on disk and executed by shelling
 * out to "scoop install|uninstall <bucket>/<app>"; Scoop itself does downloads + hash checks. */
