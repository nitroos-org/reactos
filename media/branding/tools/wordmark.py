#!/usr/bin/env python3
"""wordmark.py SRCDIR: write the NitroOS wordmark into SRCDIR as outlines of Inter Display SemiBold (SIL OFL 1.1,
SRCDIR/fonts): wordmark.svg for light grounds (navy), wordmark-reverse.svg for dark grounds (white). The dot of the
i is replaced by a small leaning bar in the flame orange, the angle of the flame in the mark.
Units are font units (2048 per em); the baseline is y=0."""
import os, sys
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

SRC = sys.argv[1]
FONT = os.path.join(SRC, 'fonts', 'InterDisplay-SemiBold.ttf')
TEXT = 'NitroOS'
KERN = {('N', 'i'): 6, ('i', 't'): 0, ('t', 'r'): -10, ('r', 'o'): -14, ('o', 'O'): 10, ('O', 'S'): 6}   # font units
TRACK = 22                    # font units added between letters (tracking for a wordmark)
LEAN = 0.40                   # horizontal shift per unit of height of the dot; the flame is 0.6, softened for a small dot
DOT_W, DOT_H = 1.0, 0.92      # dot size relative to the font own dot
DOT_DROP = 46                 # lower the dot toward the stem (font units)
ORANGE, NAVY, WHITE = '#ff7a18', '#1b1f3b', '#ffffff'

def contours(rec):
    out, cur = [], []
    for op, args in rec.value:
        cur.append((op, args))
        if op in ('closePath', 'endPath'): out.append(cur); cur = []
    return out
def path_of(ops, dx, gs):
    sp = SVGPathPen(gs); tp = TransformPen(sp, (1, 0, 0, -1, dx, 0))
    for op, args in ops: getattr(tp, op)(*args)
    return sp.getCommands()
def bounds(ops, gs):
    bp = BoundsPen(gs)
    for op, args in ops: getattr(bp, op)(*args)
    return bp.bounds

f = TTFont(FONT); gs = f.getGlyphSet(); cmap = f.getBestCmap()
xh = f['OS/2'].sxHeight; cap = f['OS/2'].sCapHeight
x = 0; prev = None; paths = []; dot = None
for ch in TEXT:
    if prev: x += KERN.get((prev, ch), 0) + TRACK
    gn = cmap[ord(ch)]; rec = DecomposingRecordingPen(gs); gs[gn].draw(rec)
    keep = []
    for c in contours(rec):
        b = bounds(c, gs)
        if ch == 'i' and b and b[1] > xh * 0.9:
            dot = (x + b[0], b[1], x + b[2], b[3]); continue
        keep += c
    paths.append(path_of(keep, x, gs))
    x += f['hmtx'][gn][0]; prev = ch
bp = BoundsPen(gs)
for ch in 'tOS':
    gs[cmap[ord(ch)]].draw(bp)
ymin = min(0, bp.bounds[1]); ymax = max(cap, dot[3], bp.bounds[3])
w = (dot[2] - dot[0]) * DOT_W; h = (dot[3] - dot[1]) * DOT_H
cx, cy = (dot[0] + dot[2]) / 2, (dot[1] + dot[3]) / 2 - DOT_DROP; sh = h * LEAN
P = [(cx - w / 2 - sh / 2, -(cy - h / 2)), (cx + w / 2 - sh / 2, -(cy - h / 2)),
     (cx + w / 2 + sh / 2, -(cy + h / 2)), (cx - w / 2 + sh / 2, -(cy + h / 2))]
dotd = 'M' + ' L'.join(f'{px:.1f} {py:.1f}' for px, py in P) + ' Z'
# the bar leans to the right: its right edge moves toward the next letter; use the bounds for the viewBox
left = min(0, P[0][0]); right = max(x, P[2][0])
top = ymax + 4; bot = -ymin + 4; W = right - left
for name, c1 in (('wordmark.svg', NAVY), ('wordmark-reverse.svg', WHITE)):
    body = '\n'.join(f'  <path fill="{c1}" d="{d}"/>' for d in paths)
    open(os.path.join(SRC, name), 'w').write(f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- NitroOS wordmark, outlines of Inter Display SemiBold (SIL OFL 1.1); generated by media/branding/tools/wordmark.py.
     Units: font units; the baseline is y=0, the cap height is y=-{cap}. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="{left:.0f} {-top:.0f} {W:.0f} {top + bot:.0f}" width="{W / 10:.1f}" height="{(top + bot) / 10:.1f}">
{body}
  <path fill="{ORANGE}" d="{dotd}"/>
</svg>
''')
    print(name, 'width', round(W), 'cap', cap, 'descender', ymin)
