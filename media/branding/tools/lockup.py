#!/usr/bin/env python3
"""lockup.py SRCDIR: compose the NitroOS lockups from mark.svg and wordmark*.svg (run marks.py and wordmark.py first).

  lockup-horizontal.svg        mark + wordmark, white wordmark, for dark grounds (boot, login, About)
  lockup-horizontal-light.svg  mark + wordmark, navy wordmark, for light grounds
  lockup-mark-only.svg         the mark alone (Start button, taskbar, icons); a copy of mark.svg

Layout (mark grid, 512 high): the wordmark's cap height is 38 % of the tile, its cap-height centre sits on the
tile's centre line, and the gap between the tile and the wordmark is 56."""
import os, re, sys

SRC = sys.argv[1]
CAP = 1490                                  # cap height of the wordmark in its own units
TILE_H = 480; SCALE = 0.38 * TILE_H / CAP; GAP = 56
def inner(name):
    s = open(os.path.join(SRC, name)).read()
    return re.search(r'<svg[^>]*>(.*)</svg>', s, re.S).group(1)
def viewbox(name):
    return [float(v) for v in re.search(r'viewBox="([^"]+)"', open(os.path.join(SRC, name)).read()).group(1).split()]
mark = inner('mark.svg')
for out, wm in (('lockup-horizontal.svg', 'wordmark-reverse.svg'), ('lockup-horizontal-light.svg', 'wordmark.svg')):
    vx, vy, vw, vh = viewbox(wm)
    # place the wordmark: its left edge (vx) at x = 496 + GAP; baseline y such that the cap-height centre is at y = 256
    tx = 496 + GAP - vx * SCALE; ty = 256 + CAP * SCALE / 2
    W = (496 + GAP) + vw * SCALE + 16
    open(os.path.join(SRC, out), 'w').write(f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- NitroOS horizontal lockup: mark + wordmark (Inter Display SemiBold outlines, SIL OFL 1.1); generated by media/branding/tools/lockup.py -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W:.0f} 512" width="{W / 2:.0f}" height="256">
<g>{mark}</g>
<g transform="translate({tx:.1f} {ty:.1f}) scale({SCALE:.5f})">{inner(wm)}</g>
</svg>
''')
    print(out, round(W))
open(os.path.join(SRC, 'lockup-mark-only.svg'), 'w').write(open(os.path.join(SRC, 'mark.svg')).read().replace('<svg ', '<!-- NitroOS mark-only lockup: Start button, taskbar, icons (identical to mark.svg) -->\n<svg ', 1))
print('lockup-mark-only.svg')
