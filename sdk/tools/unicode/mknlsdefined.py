#              calls defined) from the Unicode Character Database
# COPYRIGHT:   Copyright 2026 Tomas Srnka <tomas.srnka@e2b.dev>
#
# usage: mknlsdefined.py UnicodeData.txt > dll/win32/kernel32/winnls/string/nlsdefined.c
#
# UnicodeData.txt is the file of Unicode 6.0.0 (https://www.unicode.org/Public/6.0.0/ucd/UnicodeData.txt),
# distributed under the Unicode License (https://www.unicode.org/license.txt), which is compatible with the LGPL.
# The version is the one of the sort data of Windows 8: of the versions 5.0 to 6.2 it is the one whose assigned
# characters are closest to the points that a Windows Server 2022 reference answers TRUE for (every code point of the
# plane was asked; 58 of 54594 differ). A code point is defined when it is assigned (general category not Cn),
# no private use character (Co), no surrogate (Cs), no noncharacter (U+FDD0..U+FDEF, U+xFFFE, U+xFFFF) and not the
# byte order mark U+FEFF. U+20BA (the Turkish lira sign, Unicode 6.2) is added: it is a sample point on which the
# reference differs from the version.

import sys

EXTRA = [0x20BA]
first = None
assigned = set()
for line in open(sys.argv[1], encoding='utf-8'):
    f = line.rstrip('\n').split(';')
    cp = int(f[0], 16)
    if f[1].endswith(', First>'):
        first = cp
        continue
    last = cp
    start = cp
    if f[1].endswith(', Last>'):
        start = first
    for c in range(start, last + 1):
        if c < 0x10000 and f[2] not in ('Co', 'Cs'):
            assigned.add(c)

assigned.discard(0xFEFF)
assigned.update(EXTRA)
for c in list(assigned):
    if 0xFDD0 <= c <= 0xFDEF or (c & 0xFFFE) == 0xFFFE:
        assigned.discard(c)

ranges = []
for c in sorted(assigned):
    if ranges and ranges[-1][1] == c - 1:
        ranges[-1][1] = c
    else:
        ranges.append([c, c])

print('''/*
 * PROJECT:     ReactOS system libraries
 * LICENSE:     LGPL-2.1-or-later (https://spdx.org/licenses/LGPL-2.1-or-later)
 * PURPOSE:     The code points of the Basic Multilingual Plane that IsNLSDefinedString calls defined
 * COPYRIGHT:   Copyright 2026 Tomas Srnka <tomas.srnka@e2b.dev>
 *
 * Generated by sdk/tools/unicode/mknlsdefined.py from UnicodeData.txt of Unicode 6.0.0. Do not edit. The Unicode
 * data file is distributed under the Unicode License (https://www.unicode.org/license.txt).
 */

#include <windef.h>

/* first and last code point of each range of defined code points, in order */
const WCHAR NlsDefinedRanges[%d][2] =
{''' % len(ranges))
for i in range(0, len(ranges), 4):
    print('    ' + ' '.join('{ 0x%04X, 0x%04X },' % (a, b) for a, b in ranges[i:i + 4]))
print('};')
print()
print('const unsigned int NlsDefinedRangeCount = %d;' % len(ranges))
