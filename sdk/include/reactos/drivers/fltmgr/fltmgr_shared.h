/*
 * What FilterConnectCommunicationPort sends when it opens the communication device: an extended attribute
 * named FLT_CONNECT_EA_NAME whose value is this header followed by the name of the port (NameLength bytes
 * of UTF-16, no terminator) and the connection context (ContextSize bytes). All sizes are in bytes.
 */
#define FLT_CONNECT_EA_NAME     "FltPort"

typedef struct _FLT_CONNECT_REQUEST
{
    ULONG Options;
    USHORT NameLength;
    USHORT ContextSize;

} FLT_CONNECT_REQUEST, *PFLT_CONNECT_REQUEST;
