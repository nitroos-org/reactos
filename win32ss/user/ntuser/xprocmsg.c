/*
 * PROJECT:          ReactOS Win32k subsystem
 * PURPOSE:          Messages Windows refuses to carry from one process to another
 * COPYRIGHT:        See COPYING in the top level directory
 *
 * The tables below were measured, one message number at a time, on Windows 10 22H2 (build 19045) with a
 * black-box probe of our own (wParam 0, lParam 0, sender and receiver in different processes of the same user
 * and desktop; the result was identical for every pair of integrity levels). Each entry is a range of message
 * numbers the sender is refused, with the error SetLastError() shows. Messages not listed are not changed.
 * XE_SILENT entries are messages Windows swallows without any error (the call returns FALSE, or TRUE for a few
 * posts, and the receiver never sees the message) when wParam and lParam are both 0, as measured; with other
 * parameters nothing is changed, because nothing else was measured.
 * Only user-initiated calls (NtUserPostMessage, NtUserPostThreadMessage, NtUserMessageCall) are checked;
 * messages win32k sends on its own never pass through here.
 */

