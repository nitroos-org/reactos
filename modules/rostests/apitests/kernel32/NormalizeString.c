/* the answer of a call to NormalizeString */
typedef struct
{
    int Ret;
    DWORD Error;
    WCHAR Buf[600];
} ANSWER;

static void Call(ANSWER *A, int Form, const WCHAR *Src, int SrcLen, int DstLen, int NoDst)
{
    int i;

    for (i = 0; i < 600; i++)
        A->Buf[i] = 0xAAAA;
    SetLastError(UNTOUCHED);
    A->Ret = pNormalizeString(Form, Src, SrcLen, NoDst ? NULL : A->Buf, DstLen);
    A->Error = GetLastError();
}

/* the units written to the buffer: up to the first that was not */
static int Written(const ANSWER *A)
{
    int n = 0;

    while (n < 600 && A->Buf[n] != 0xAAAA)
        n++;
    return n;
}

static int HasNul(const WCHAR *Src, int Count)
{
    int i;

    for (i = 0; i < Count; i++)
        if (!Src[i])
            return 1;
    return 0;
}

static void TestVectors(void)
{
    static const int Forms[4] = { 1, 2, 5, 6 };
    unsigned i;
    int k;

    for (i = 0; i < ARRAYSIZE(Vectors); i++)
    {
        WCHAR Src[64], SrcNul[64];
        int n = Units(Vectors[i].Src, Src);

        memcpy(SrcNul, Src, n * sizeof(WCHAR));
        SrcNul[n] = 0;
        for (k = 0; k < 4; k++)
        {
            const char *Result = Vectors[i].Result[k];
            int Form = Forms[k], Compat = k >= 2, Failed = Result[0] == '!', RetExplicit = 0, RetNul = 0, Count;
            const char *Hex = Result;
            WCHAR Want[600];
            ANSWER A;
            BOOL Is;
            DWORD Error;

            if (Failed)
            {
                char *End;

                RetExplicit = strtol(Result + 1, &End, 10);
                RetNul = strtol(End + 1, &End, 10);
                Hex = End + 1;
            }
            Count = Units(Hex, Want);

            /* the length given */
            Call(&A, Form, Src, n, 500, 0);
            if (!Failed)
            {
                ok(A.Ret == Count && A.Error == 0, "%s/%d: returned %d (%lu), expected %d\n", Vectors[i].Name, Form, A.Ret, A.Error, Count);
                ok(Written(&A) == Count && !memcmp(A.Buf, Want, Count * sizeof(WCHAR)), "%s/%d: wrong result\n", Vectors[i].Name, Form);
            }
            else
            {
                ok(A.Ret == RetExplicit && A.Error == ERROR_NO_UNICODE_TRANSLATION, "%s/%d: returned %d (%lu), expected %d (1113)\n",
                   Vectors[i].Name, Form, A.Ret, A.Error, RetExplicit);
                ok(Written(&A) == Count && !memcmp(A.Buf, Want, Count * sizeof(WCHAR)), "%s/%d: wrong units before the invalid one\n", Vectors[i].Name, Form);
            }

            /* a length of -1: the NUL is part of the source and of the result */
            if (!HasNul(Src, n))
            {
                Call(&A, Form, SrcNul, -1, 500, 0);
                if (!Failed)
                {
                    Want[Count] = 0;
                    ok(A.Ret == Count + 1 && A.Error == 0, "%s/%d (-1): returned %d (%lu), expected %d\n", Vectors[i].Name, Form, A.Ret, A.Error, Count + 1);
                    ok(Written(&A) == Count + 1 && !memcmp(A.Buf, Want, (Count + 1) * sizeof(WCHAR)), "%s/%d (-1): wrong result\n", Vectors[i].Name, Form);
                }
                else
                {
                    ok(A.Ret == RetNul && A.Error == ERROR_NO_UNICODE_TRANSLATION, "%s/%d (-1): returned %d (%lu), expected %d (1113)\n",
                       Vectors[i].Name, Form, A.Ret, A.Error, RetNul);
                    ok(Written(&A) == Count && !memcmp(A.Buf, Want, Count * sizeof(WCHAR)), "%s/%d (-1): wrong units before the invalid one\n", Vectors[i].Name, Form);
                }
            }

            /* the size query does not look at the string */
            Call(&A, Form, Src, n, 0, 0);
            ok(A.Ret == Estimate(Compat, n) && A.Error == 0 && Written(&A) == 0, "%s/%d: size query %d (%lu), expected %d\n", Vectors[i].Name, Form, A.Ret, A.Error, Estimate(Compat, n));
            if (!HasNul(Src, n))
            {
                Call(&A, Form, SrcNul, -1, 0, 1);
                ok(A.Ret == Estimate(Compat, n + 1) && A.Error == 0, "%s/%d (-1): size query %d (%lu), expected %d\n", Vectors[i].Name, Form, A.Ret, A.Error, Estimate(Compat, n + 1));
            }

            /* IsNormalizedString: false for an invalid string (the error), else whether the source is the result;
               the last error is not touched when it is not an error */
            SetLastError(UNTOUCHED);
            Is = pIsNormalizedString(Form, Src, n);
            Error = GetLastError();
            if (Failed)
            {
                ok(!Is && Error == ERROR_NO_UNICODE_TRANSLATION, "%s/%d: IsNormalizedString %d (%lu)\n", Vectors[i].Name, Form, Is, Error);
            }
            else
            {
                BOOL Expected = Count == n && !memcmp(Want, Src, n * sizeof(WCHAR));

                ok((Is != FALSE) == Expected && Error == UNTOUCHED, "%s/%d: IsNormalizedString %d (%lu), expected %d\n", Vectors[i].Name, Form, Is, Error, Expected);
            }
            if (!HasNul(Src, n) && n)
            {
                SetLastError(UNTOUCHED);
                Is = pIsNormalizedString(Form, SrcNul, -1);
                Error = GetLastError();
                if (Failed)
                    ok(!Is && Error == ERROR_NO_UNICODE_TRANSLATION, "%s/%d (-1): IsNormalizedString %d (%lu)\n", Vectors[i].Name, Form, Is, Error);
                else
                    ok((Is != FALSE) == (Count == n && !memcmp(Want, Src, n * sizeof(WCHAR))) && Error == UNTOUCHED,
                       "%s/%d (-1): IsNormalizedString %d (%lu)\n", Vectors[i].Name, Form, Is, Error);
            }
        }
    }
}

