/* the units of a string of hexadecimal numbers */
static int Units(const char *Hex, WCHAR *Out)
{
    int n = 0;

    while (*Hex)
    {
        while (*Hex == ' ')
            Hex++;
        if (!*Hex)
            break;
        Out[n++] = (WCHAR)strtoul(Hex, (char **)&Hex, 16);
    }
    return n;
}

/* what NormalizeString answers to the size query: 3 units for each of the source (18 for the compatibility
   forms and the nameprep), but not more than the length plus an eighth of it, and that not below 64 */
static int Estimate(int Compat, int Length)
{
    long long ByFactor = (long long)Length * (Compat ? 18 : 3);
    long long ByGrowth = Length + Length / 8;

    if (ByGrowth < 64)
        ByGrowth = 64;
    return (int)(ByFactor < ByGrowth ? ByFactor : ByGrowth);
}

