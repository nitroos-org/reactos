START_TEST(GetTimeFormat)
{
    ULONG i;
    WCHAR Buffer[128];
    SYSTEMTIME Time = { 2026, 11, 3, 4, 0, 0, 0, 0 };
    int Ret, Size;

    for (i = 0; i < ARRAYSIZE(g_Cases); ++i)
    {
        if (!IsValidLocale(g_Cases[i].Lcid, LCID_INSTALLED))
        {
            skip("Locale %04lx is not installed\n", g_Cases[i].Lcid);
            continue;
        }
        Time.wHour = g_Cases[i].Hour;
        Time.wMinute = g_Cases[i].Minute;
        Time.wSecond = g_Cases[i].Second;

        RtlFillMemory(Buffer, sizeof(Buffer), 0xcc);
        SetLastError(0xdeadbeef);
        Ret = GetTimeFormatW(g_Cases[i].Lcid, g_Cases[i].Flags, &Time, g_Cases[i].Format, Buffer, ARRAYSIZE(Buffer));
        if (!Ret || wcscmp(Buffer, g_Cases[i].Expected) != 0)
        {
            ok(0, "[%lu] lcid %04lx flags %08lx format '%ls' %02u:%02u:%02u: got '%ls' (%d, error %lu), expected '%ls'\n",
               i, g_Cases[i].Lcid, g_Cases[i].Flags, g_Cases[i].Format ? g_Cases[i].Format : L"(default)",
               Time.wHour, Time.wMinute, Time.wSecond, Ret ? Buffer : L"", Ret, GetLastError(), g_Cases[i].Expected);
            continue;
        }
        ok(Ret == (int)wcslen(g_Cases[i].Expected) + 1, "[%lu] returned %d\n", i, Ret);

        /* The size query must agree with the string */
        SetLastError(0xdeadbeef);
        Size = GetTimeFormatW(g_Cases[i].Lcid, g_Cases[i].Flags, &Time, g_Cases[i].Format, NULL, 0);
        ok(Size == Ret, "[%lu] lcid %04lx flags %08lx format '%ls': size query returned %d, expected %d\n",
           i, g_Cases[i].Lcid, g_Cases[i].Flags, g_Cases[i].Format ? g_Cases[i].Format : L"(default)", Size, Ret);
    }
}
