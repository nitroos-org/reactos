START_TEST(ChainServerName)
{
    PCCERT_CONTEXT Cert = NULL;
    const BYTE *Current = NULL;
    DWORD i;

    for (i = 0; i < ARRAYSIZE(Rows); i++)
    {
        const NAME_ROW *Row = &Rows[i];
        PCCERT_CHAIN_CONTEXT Chain = NULL;
        CERT_CHAIN_PARA Para;
        HTTPSPolicyCallbackData Ssl;
        CERT_CHAIN_POLICY_PARA PolicyPara;
        CERT_CHAIN_POLICY_STATUS PolicyStatus;
        BOOL Ret;

        if (Current != Row->Cert)
        {
            if (Cert)
                CertFreeCertificateContext(Cert);
            Cert = CertCreateCertificateContext(X509_ASN_ENCODING, Row->Cert, Row->Size);
            Current = Row->Cert;
            ok(Cert != NULL, "CertCreateCertificateContext failed: %lu\n", GetLastError());
            if (!Cert)
                return;
        }

        memset(&Para, 0, sizeof(Para));
        Para.cbSize = sizeof(Para);
        Ret = CertGetCertificateChain(NULL, Cert, NULL, NULL, &Para, 0, NULL, &Chain);
        ok(Ret, "row %lu: CertGetCertificateChain failed: %lu\n", i, GetLastError());
        if (!Ret)
            continue;

        memset(&Ssl, 0, sizeof(Ssl));
        Ssl.cbSize = sizeof(Ssl);
        Ssl.dwAuthType = AUTHTYPE_SERVER;
        Ssl.fdwChecks = SECURITY_FLAG_IGNORE_UNKNOWN_CA | SECURITY_FLAG_IGNORE_CERT_DATE_INVALID;
        Ssl.pwszServerName = (WCHAR *)Row->Name;
        memset(&PolicyPara, 0, sizeof(PolicyPara));
        PolicyPara.cbSize = sizeof(PolicyPara);
        PolicyPara.pvExtraPolicyPara = &Ssl;
        memset(&PolicyStatus, 0, sizeof(PolicyStatus));
        PolicyStatus.cbSize = sizeof(PolicyStatus);
        Ret = CertVerifyCertificateChainPolicy(CERT_CHAIN_POLICY_SSL, Chain, &PolicyPara, &PolicyStatus);
        ok(Ret, "row %lu: CertVerifyCertificateChainPolicy failed: %lu\n", i, GetLastError());
        if (Ret)
        {
            if (Row->Match)
                ok(PolicyStatus.dwError == 0, "row %lu (%ls): error %08lx, expected a match\n",
                   i, Row->Name, PolicyStatus.dwError);
            else
                ok(PolicyStatus.dwError == CERT_E_CN_NO_MATCH, "row %lu (%ls): error %08lx, expected CERT_E_CN_NO_MATCH\n",
                   i, Row->Name, PolicyStatus.dwError);
        }
        CertFreeCertificateChain(Chain);
    }

    if (Cert)
        CertFreeCertificateContext(Cert);
}
