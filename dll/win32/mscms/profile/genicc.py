#!/usr/bin/env python3
# PROJECT:     ReactOS Color Management (mscms.dll)
# LICENSE:     CC0-1.0 (the generator and the profile it writes are dedicated to the public domain)
# PURPOSE:     Write sRGB_Color_Space_Profile.icm: a small ICC v2.1 matrix/TRC display profile for sRGB
# COPYRIGHT:   Copyright 2026 Tomas Srnka <tomas.srnka@e2b.dev>
#
# Provenance: every number below comes from public standards, nothing is copied from another profile.
#  - transfer curve: the sRGB EOTF of IEC 61966-2-1 (linear toe 12.92, offset 0.055, exponent 2.4),
#    sampled at 1024 points
#  - colorants: the sRGB primaries (Rec. 709 chromaticities) adapted from D65 to the ICC D50 profile
#    connection space with the Bradford transform; the resulting matrix is the one printed in the ICC
#    sRGB documentation and in common colour-science references (columns R, G, B):
#      0.4360747 0.3850649 0.1430804 / 0.2225045 0.7168786 0.0606169 / 0.0139322 0.0971045 0.7141733
#  - white point: D50 as the ICC specifies it (0.9642, 1.0, 0.8249)
# Run: python3 genicc.py OUTFILE   (deterministic: same bytes every time)
import struct, sys

def s15(x): return struct.pack('>i', int(round(x * 65536.0)))
def xyz(x, y, z): return b'XYZ \0\0\0\0' + s15(x) + s15(y) + s15(z)
def text(s): b = s.encode('ascii') + b'\0'; return b'text\0\0\0\0' + b
def desc(s):
    b = s.encode('ascii') + b'\0'
    return b'desc\0\0\0\0' + struct.pack('>I', len(b)) + b + struct.pack('>II', 0, 0) + struct.pack('>HB', 0, 0) + b'\0' * 67
def srgb(v): return v * 12.92 if v <= 0.0031308 else 1.055 * v ** (1 / 2.4) - 0.055
def srgb_eotf(e): return e / 12.92 if e <= 0.04045 else ((e + 0.055) / 1.055) ** 2.4
def curv():
    n = 1024
    return b'curv\0\0\0\0' + struct.pack('>I', n) + b''.join(struct.pack('>H', int(round(srgb_eotf(i / (n - 1)) * 65535))) for i in range(n))

D50 = (0.9642, 1.0, 0.8249)
tags = [
    (b'cprt', text('Public domain (CC0-1.0). Generated by genicc.py of ReactOS mscms.')),
    (b'desc', desc('sRGB Color Space Profile')),
    (b'wtpt', xyz(*D50)),
    (b'rXYZ', xyz(0.4360747, 0.2225045, 0.0139322)),
    (b'gXYZ', xyz(0.3850649, 0.7168786, 0.0971045)),
    (b'bXYZ', xyz(0.1430804, 0.0606169, 0.7141733)),
    (b'rTRC', curv()), (b'gTRC', curv()), (b'bTRC', curv()),
]
# tags share the curve data when identical (the ICC allows it)
table = b''; body = b''; off = 128 + 4 + 12 * len(tags); seen = {}
for sig, data in tags:
    pad = (-len(data)) % 4; blob = data + b'\0' * pad
    if blob in seen: o = seen[blob]
    else: o = off + len(body); seen[blob] = o; body += blob
    table += sig + struct.pack('>II', o, len(data))
size = off + len(body)
hdr = struct.pack('>I', size) + b'\0\0\0\0' + struct.pack('>I', 0x02100000) + b'mntr' + b'RGB ' + b'XYZ '
hdr += struct.pack('>6H', 2026, 11, 12, 0, 0, 0) + b'acsp' + b'\0\0\0\0' + struct.pack('>I', 0) + b'\0\0\0\0' * 2 + struct.pack('>II', 0, 0)
hdr += struct.pack('>I', 0) + s15(D50[0]) + s15(D50[1]) + s15(D50[2]) + b'\0\0\0\0' + b'\0' * 44
assert len(hdr) == 128, len(hdr)
open(sys.argv[1], 'wb').write(hdr + struct.pack('>I', len(tags)) + table + body)
