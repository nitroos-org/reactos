#!/usr/bin/env python3
"""Generate ctype3_data.h for GetStringTypeW(CT_CTYPE3).

Usage: mkctype3.py > ctype3_data.h

Input: the Unicode character database as shipped in Python's unicodedata module
(the version is written into the header). Only facts about characters are used
(general category); the flag assignment follows measurements of GetStringTypeW
on Windows 10 (U+0024, 005F, 00A1, 00A2, 00A6, 00A8, 00AB, 00AC, 00BB, 0300,
02B0, 02C2, 0482, 0F3A, 0F3B, 2044, 20A0, 20DD, 203F, 2E02, 2E0A, 301C, 3001)
and is limited to what those measurements show:
  C3_NONSPACING (0x1)  Mn, Me
  C3_DIACRITIC  (0x2)  Sk, Lm, and the Combining Diacritical Marks block 0300-036F
  C3_SYMBOL     (0x8)  Sc, Sm, Sk, So; Latin-1 (0080-00FF) punctuation
Only the BMP above U+007F is covered, surrogates and unassigned characters get no
flags here (locale.c masks with C1_DEFINED). The caller ORs these flags into the
ones it derives elsewhere.
"""
import sys, unicodedata

NONSPACING, DIACRITIC, SYMBOL = 0x1, 0x2, 0x8

def flags(c):
    if 0xd800 <= c <= 0xdfff:
        return 0
    cat = unicodedata.category(chr(c))
    f = 0
    if cat in ('Mn', 'Me'):
        f |= NONSPACING
    if cat in ('Sk', 'Lm') or 0x300 <= c <= 0x36f:
        f |= DIACRITIC
    if cat in ('Sc', 'Sm', 'Sk', 'So') or (0x80 <= c <= 0xff and cat.startswith('P')):
        f |= SYMBOL
    return f

runs = []
for c in range(0x80, 0x10000):
    f = flags(c)
    if not f:
        continue
    if runs and runs[-1][1] == c - 1 and runs[-1][2] == f:
        runs[-1][1] = c
    else:
        runs.append([c, c, f])

out = []
out.append('/* Generated by mkctype3.py from Unicode %s (Python unicodedata); DO NOT EDIT. */' % unicodedata.unidata_version)
out.append('')
out.append('struct ctype3_range { WCHAR first, last; WORD flags; };')
out.append('')
out.append('static const struct ctype3_range ctype3_ranges[] =')
out.append('{')
line = '   '
for lo, hi, f in runs:
    item = ' { 0x%04x, 0x%04x, 0x%x },' % (lo, hi, f)
    if len(line) + len(item) > 100:
        out.append(line)
        line = '   '
    line += item
out.append(line)
out.append('};')
print('\n'.join(out))
sys.stderr.write('%d ranges\n' % len(runs))
